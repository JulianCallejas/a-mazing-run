import { MAZE_CELLS } from '../utils/constants';

export class MazeGenerator {
  private maze: number[][];
  private width: number;
  private height: number;

  constructor(width: number, height: number) {
    this.width = width;
    this.height = height;
    this.maze = [];
  }

  public generateMaze(): number[][] {
    // Initialize maze with walls
    this.maze = Array(this.height).fill(null).map(() => 
      Array(this.width).fill(MAZE_CELLS.WALL)
    );

    // Use recursive backtracking to generate paths
    this.carvePassages(1, 1);
    
    // Set start and exit positions
    this.maze[1][1] = MAZE_CELLS.START;
    this.maze[this.height - 2][this.width - 2] = MAZE_CELLS.EXIT;

    return this.maze;
  }

  private carvePassages(x: number, y: number): void {
    const directions = [
      [0, -2], [2, 0], [0, 2], [-2, 0]
    ];
    
    // Shuffle directions for randomness
    this.shuffleArray(directions);
    
    this.maze[y][x] = MAZE_CELLS.PATH;

    for (const [dx, dy] of directions) {
      const nx = x + dx;
      const ny = y + dy;
      
      if (this.isValidCell(nx, ny) && this.maze[ny][nx] === MAZE_CELLS.WALL) {
        // Carve passage between current cell and next cell
        this.maze[y + dy / 2][x + dx / 2] = MAZE_CELLS.PATH;
        this.carvePassages(nx, ny);
      }
    }
  }

  private isValidCell(x: number, y: number): boolean {
    return x > 0 && x < this.width - 1 && y > 0 && y < this.height - 1;
  }

  private shuffleArray<T>(array: T[]): void {
    for (let i = array.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [array[i], array[j]] = [array[j], array[i]];
    }
  }
}

